/* Consulta embebida en Power Query (tabla 'Origen Estados').
   Origen: Sql.Database("SERVIDOR_DW\\DATAWAREHOUSE", "PRESUPUESTO_CONTABILIDAD_DM").
   Servidores y codigo de sociedad reemplazados por marcadores. */

SELECT	CONCAT(BASE.DIA,'/', BASE.MES,'/', BASE.ANIO COLLATE Latin1_General_BIN) FECHA	
		 ,BASE.CODIGO_CONTABLE
		 ,LEFT(BASE.CODIGO_CONTABLE,5) CODIGO_CONTABLE_5
		 ,BASE.VALOR
		 ,BASE.INDICADOR
		 ,BASE.CODIGO_CONTABLE AS [CODIGO_CONTABLE NUM]
		 ,LEFT(BASE.CODIGO_CONTABLE,1) AS ORDEN
FROM(
	SELECT  DIA = 1, MES, ANIO, CODIGO_CONTABLE,INDICADOR, VALOR
FROM (  
    select  FACT.RYEAR AS ANIO
		,FACT.RACCT as CODIGO_CONTABLE
		,FACT.DRCRK AS INDICADOR

		,SUM(FACT.TSLVT)+SUM(FACT.TSL01) ENERO	
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02) FEBRERO
		 ,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03) MARZO
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04) ABRIL
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05) MAYO
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06) JUNIO
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07) JULIO
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08) AGOSTO
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)+SUM(FACT.TSL09) SEPTIEMBRE
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)+SUM(FACT.TSL09)+SUM(FACT.TSL10) OCTUBRE
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)+SUM(FACT.TSL09)+SUM(FACT.TSL10)+SUM(FACT.TSL11) NOVIEMBRE
		,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)+SUM(FACT.TSL09)+SUM(FACT.TSL10)+SUM(FACT.TSL11)+SUM(FACT.TSL12) DICIEMBRE
		--,SUM(FACT.TSLVT)+SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)
		--				+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)
		--				+SUM(FACT.TSL09)+SUM(FACT.TSL10)+SUM(FACT.TSL11)+SUM(FACT.TSL12) AS TOTAL
	
FROM [SERVIDOR_SAP].[PRD].[prd].[FAGLFLEXT] FACT

where RYEAR >= 2023
	AND FACT.RCLNT = 400
	AND FACT.RBUKRS LIKE 'EMP1'
GROUP BY  FACT.RYEAR, FACT.RACCT, FACT.DRCRK
HAVING SUM(FACT.TSLVT) +SUM(FACT.TSL01)+SUM(FACT.TSL02)+SUM(FACT.TSL03)+SUM(FACT.TSL04)
						+SUM(FACT.TSL05)+SUM(FACT.TSL06)+SUM(FACT.TSL07)+SUM(FACT.TSL08)
						+SUM(FACT.TSL09)+SUM(FACT.TSL10)+SUM(FACT.TSL11)+SUM(FACT.TSL12) <> 0
						--AND FACT.RACCT LIKE '1111501012' 
) p  
UNPIVOT (  
    VALOR FOR MES IN (ENERO,FEBRERO, MARZO, ABRIL, MAYO, JUNIO, JULIO, AGOSTO, SEPTIEMBRE, OCTUBRE, NOVIEMBRE, DICIEMBRE)  
) AS unpvt  

WHERE VALOR <> 0
--	AND MES LIKE 'DICIEMBRE'
--	AND AÑO LIKE '2024'
--	AND CODIGO_CONTABLE LIKE '11215%'
--ORDER BY AÑO, MES;
	) BASE
