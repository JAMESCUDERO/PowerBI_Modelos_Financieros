/* Consulta embebida en Power Query (tabla 'Ingresos PRE').
   Origen: Sql.Database("SERVIDOR_DW\\DATAWAREHOUSE", "PRESUPUESTO_CONTABILIDAD_DM").
   Servidores y codigo de sociedad reemplazados por marcadores. */

SELECT CONCAT(DIA,'/',MES,'/', DOCYEAR COLLATE Latin1_General_BIN) FECHA
		, left(CMMTITEM,6) CMMTITEM, PROCESS , VALOR

FROM (
SELECT  DIA=1
		,DOCYEAR
		,CMMTITEM
		--,BUDCAT
		--,PROCESS
		,PROCESS	=CASE WHEN (BUDCAT = '9F' AND PROCESS LIKE 'ENTR') THEN 'PRESUPUESTO'
						  WHEN (BUDCAT = '9F' AND PROCESS LIKE 'RETN') THEN 'TRASPASO REDUCCION'
						  WHEN (BUDCAT = '9F' AND PROCESS LIKE 'SUPL') THEN 'TRASPASO INCREMENTO'
						 
						  WHEN (BUDCAT = '9G' AND PROCESS LIKE 'RETN') THEN 'REDUCCION'
						  WHEN (BUDCAT = '9G' AND PROCESS LIKE 'SUPL') THEN 'INCREMENTO'
						  
						  
					 END
		,ENERO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01) ELSE SUM(TVAL01) END
		,FEBRERO	= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)ELSE SUM(TVAL02) END
		,MARZO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03) ELSE SUM(TVAL03) END
		,ABRIL		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04) ELSE SUM(TVAL04) END
		,MAYO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05) ELSE SUM(TVAL05) END
		,JUNIO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06) ELSE SUM(TVAL06) END
		,JULIO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07) ELSE SUM(TVAL07) END
		,AGOSTO		= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07)+SUM(TVAL08) ELSE SUM(TVAL08) END
		,SEPTIEMBRE	= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07)+SUM(TVAL08)+SUM(TVAL09) ELSE SUM(TVAL09) END
		,OCTUBRE	= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07)+SUM(TVAL08)+SUM(TVAL09)+SUM(TVAL10) ELSE SUM(TVAL10) END
		,NOVIEMBRE  = CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07)+SUM(TVAL08)+SUM(TVAL09)+SUM(TVAL10)+SUM(TVAL11) ELSE SUM(TVAL11) END
		,DICIEMBRE	= CASE WHEN BUDCAT LIKE '9F' THEN SUM(TVAL01)+SUM(TVAL02)+SUM(TVAL03)+SUM(TVAL04)+SUM(TVAL05)+SUM(TVAL06)+SUM(TVAL07)+SUM(TVAL08)+SUM(TVAL09)+SUM(TVAL10)+SUM(TVAL11)+SUM(TVAL12) ELSE SUM(TVAL12) END

FROM [SERVIDOR_SAP].[PRD].[prd].[FMBL]
where DOCYEAR > 2022
	AND CLIENT =400
	--AND LEFT(CMMTITEM,1) IN ('1', '2', '3')
	AND CMMTITEM BETWEEN '100000' AND '399999'
	--AND CMMTITEM =  380108
	AND	(BUDCAT = '9F' 
	OR	(BUDCAT = '9G' AND PROCESS LIKE 'RETN')
	OR	(BUDCAT = '9G' AND PROCESS LIKE 'SUPL'))
	--AND FUNDSCTR =3290
	GROUP BY 
		DOCYEAR, CMMTITEM ,BUDCAT, PROCESS

)p
UNPIVOT (  
    VALOR FOR MES IN (ENERO,FEBRERO, MARZO, ABRIL, MAYO, JUNIO, JULIO, AGOSTO, SEPTIEMBRE, OCTUBRE, NOVIEMBRE, DICIEMBRE)  
) AS unpvt  
WHERE VALOR <>0
