/* Consulta embebida en Power Query (tabla 'Verificacion_Contable').
   Origen: Sql.Database("SERVIDOR_DW\\DATAWAREHOUSE", "PRESUPUESTO_CONTABILIDAD_DM").
   Servidores y codigo de sociedad reemplazados por marcadores. */

SELECT	CONCAT(BASE.DIA,'/', BASE.MES,'/', BASE.ANIO COLLATE Latin1_General_BIN) FECHA	
		 ,BASE.CODIGO_CONTABLE
		 ,LEFT(BASE.CODIGO_CONTABLE,5) CODIGO_CONTABLE_5
		 ,BASE.VALOR
		 ,BASE.INDICADOR
		 ,BASE.CODIGO_CONTABLE AS [CODIGO_CONTABLE NUM]
		 ,LEFT(BASE.CODIGO_CONTABLE,1) AS ORDEN
FROM(
	SELECT  DIA = 1, MES, ANIO, CODIGO_CONTABLE, VALOR, INDICADOR
FROM (  
    select  FACT.RYEAR AS ANIO
		,FACT.RACCT as CODIGO_CONTABLE
		,FACT.DRCRK AS INDICADOR

		,SUM(FACT.TSLVT)ENERO	
		,SUM(FACT.TSLVT) FEBRERO
		,SUM(FACT.TSLVT) MARZO
		,SUM(FACT.TSLVT) ABRIL
		,SUM(FACT.TSLVT) MAYO
		,SUM(FACT.TSLVT) JUNIO
		,SUM(FACT.TSLVT) JULIO
		,SUM(FACT.TSLVT) AGOSTO
		,SUM(FACT.TSLVT) SEPTIEMBRE
		,SUM(FACT.TSLVT) OCTUBRE
		,SUM(FACT.TSLVT) NOVIEMBRE
		,SUM(FACT.TSLVT) DICIEMBRE	
FROM [SERVIDOR_SAP].[PRD].[prd].[FAGLFLEXT] FACT

where RYEAR >= 2023
	AND FACT.RCLNT = 400
	AND FACT.RBUKRS LIKE 'EMP1'
GROUP BY  FACT.RYEAR, FACT.RACCT, FACT.DRCRK
HAVING SUM(FACT.TSLVT) <> 0
						--AND FACT.RACCT LIKE '1111501012' 
) p  
UNPIVOT (  
    VALOR FOR MES IN (ENERO,FEBRERO, MARZO, ABRIL, MAYO, JUNIO, JULIO, AGOSTO, SEPTIEMBRE, OCTUBRE, NOVIEMBRE, DICIEMBRE)  
) AS unpvt  

WHERE VALOR <> 0

	) BASE
